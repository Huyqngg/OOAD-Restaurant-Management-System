    TrangThai VARCHAR(30) NOT NULL DEFAULT 'HOAT_DONG' CHECK (TrangThai IN ('HOAT_DONG','NGUNG_HOAT_DONG')),
    NgayTao DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    RowVer ROWVERSION
);
GO

CREATE TABLE BanAn(
    MaBan INT IDENTITY(1,1) PRIMARY KEY,
    MaBanCode VARCHAR(20) NOT NULL UNIQUE,
