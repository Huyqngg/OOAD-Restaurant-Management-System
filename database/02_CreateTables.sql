CREATE TABLE NhanVien(
    MaNhanVien INT IDENTITY(1,1) PRIMARY KEY,
    MaNhanVienCode VARCHAR(20) NOT NULL UNIQUE,
    HoTen NVARCHAR(120) NOT NULL,
    CCCD VARCHAR(20) NULL UNIQUE,
    SDT VARCHAR(20) NULL,
    Email VARCHAR(150) NULL,
    DiaChi NVARCHAR(250) NULL,
    VaiTro VARCHAR(30) NOT NULL CHECK (VaiTro IN ('CHU_NHA_HANG','PHUC_VU','DAU_BEP','THU_NGAN')),
    TrangThaiLamViec VARCHAR(30) NOT NULL DEFAULT 'DANG_LAM' CHECK (TrangThaiLamViec IN ('DANG_LAM','TAM_NGHI','DA_NGHI')),
    NgayTao DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    RowVer ROWVERSION
);
GO

CREATE TABLE TaiKhoan(
    MaTaiKhoan INT IDENTITY(1,1) PRIMARY KEY,
    TenDangNhap VARCHAR(80) NOT NULL UNIQUE,
    MatKhauHash VARCHAR(255) NOT NULL,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'HOAT_DONG' CHECK (TrangThai IN ('HOAT_DONG','BI_KHOA','VO_HIEU_HOA')),
    MaNhanVien INT NOT NULL UNIQUE,
    MaOTP VARCHAR(10) NULL,
    HanOTP DATETIME2 NULL,
    SoLanNhapSaiOTP INT NOT NULL DEFAULT 0 CHECK (SoLanNhapSaiOTP >= 0),
    SoLanDangNhapSai INT NOT NULL DEFAULT 0 CHECK (SoLanDangNhapSai >= 0),
    KhoaDen DATETIME2 NULL,
    LanDangNhapCuoi DATETIME2 NULL,
    CONSTRAINT FK_TaiKhoan_NhanVien FOREIGN KEY(MaNhanVien) REFERENCES NhanVien(MaNhanVien)
);
GO

CREATE TABLE KhachHang(
    MaKhachHang INT IDENTITY(1,1) PRIMARY KEY,
    MaKhachHangCode VARCHAR(20) NOT NULL UNIQUE,
    HoTen NVARCHAR(120) NOT NULL,
