GO

CREATE TABLE KhuyenMai(
    MaKM INT IDENTITY(1,1) PRIMARY KEY,
    MaKMCode VARCHAR(30) NOT NULL UNIQUE,
    TenKM NVARCHAR(150) NOT NULL,
    LoaiKM VARCHAR(30) NOT NULL CHECK (LoaiKM IN ('PHAN_TRAM','SO_TIEN','MON_PHAN_TRAM','MUA_X_TANG_Y')),
    GiaTriGiam DECIMAL(18,2) NOT NULL CHECK (GiaTriGiam >= 0),
    DieuKienToiThieu DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK (DieuKienToiThieu >= 0),
    MucGiamToiDa DECIMAL(18,2) NULL CHECK (MucGiamToiDa IS NULL OR MucGiamToiDa >= 0),
    NgayBatDau DATE NOT NULL,
    NgayKetThuc DATE NOT NULL,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'HOAT_DONG' CHECK (TrangThai IN ('HOAT_DONG','NGUNG_AP_DUNG')),
    MaMonMucTieu INT NULL,
    SoLuongMua INT NULL,
    SoLuongTang INT NULL,
    CONSTRAINT CK_KhuyenMai_Ngay CHECK (NgayKetThuc >= NgayBatDau),
    CONSTRAINT FK_KhuyenMai_Mon FOREIGN KEY(MaMonMucTieu) REFERENCES MonAn(MaMon)
);
GO

CREATE TABLE HoaDon(
    MaHoaDon BIGINT IDENTITY(1,1) PRIMARY KEY,
    MaHoaDonCode VARCHAR(30) NOT NULL UNIQUE,
    MaPhieu BIGINT NOT NULL UNIQUE,
    MaKhachHang INT NULL,
    MaNhanVienThuNgan INT NOT NULL,
    MaKM INT NULL,
    NgayGioLap DATETIME2 NOT NULL DEFAULT SYSDATETIME(),
    TyLeVAT DECIMAL(8,6) NOT NULL DEFAULT 0.08 CHECK (TyLeVAT >= 0),
    TamTinh DECIMAL(18,2) NOT NULL CHECK (TamTinh >= 0),
    TienGiamKhuyenMai DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK (TienGiamKhuyenMai >= 0),
    TienGiamDiem DECIMAL(18,2) NOT NULL DEFAULT 0 CHECK (TienGiamDiem >= 0),
    TongThanhToan DECIMAL(18,2) NOT NULL CHECK (TongThanhToan >= 0),
    DiemDaDung INT NOT NULL DEFAULT 0 CHECK (DiemDaDung >= 0),
    DiemTichMoi INT NOT NULL DEFAULT 0 CHECK (DiemTichMoi >= 0),
    HinhThucThanhToan VARCHAR(30) NOT NULL CHECK (HinhThucThanhToan IN ('TIEN_MAT','CHUYEN_KHOAN','THE','KET_HOP')),
    TienKhachTra DECIMAL(18,2) NOT NULL CHECK (TienKhachTra >= 0),
    TrangThaiThanhToan VARCHAR(30) NOT NULL DEFAULT 'DA_THANH_TOAN' CHECK (TrangThaiThanhToan IN ('DA_THANH_TOAN','DA_HUY','HOAN_TIEN')),
    CONSTRAINT FK_HoaDon_Phieu FOREIGN KEY(MaPhieu) REFERENCES PhieuGoiMon(MaPhieu),
    CONSTRAINT FK_HoaDon_KhachHang FOREIGN KEY(MaKhachHang) REFERENCES KhachHang(MaKhachHang),
    CONSTRAINT FK_HoaDon_ThuNgan FOREIGN KEY(MaNhanVienThuNgan) REFERENCES NhanVien(MaNhanVien),
    CONSTRAINT FK_HoaDon_KhuyenMai FOREIGN KEY(MaKM) REFERENCES KhuyenMai(MaKM)
);
GO

