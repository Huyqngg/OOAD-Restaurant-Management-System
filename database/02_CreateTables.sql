);
GO

CREATE TABLE DatBan(
    MaDatBan BIGINT IDENTITY(1,1) PRIMARY KEY,
    MaBan INT NOT NULL,
    MaKhachHang INT NULL,
    MaNhanVien INT NOT NULL,
    TenNguoiDat NVARCHAR(120) NOT NULL,
